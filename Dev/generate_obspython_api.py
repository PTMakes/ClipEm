#!/usr/bin/env python3
"""
Writes PTMClipEm-App/tests/obspython_api.json: every name OBS's `obspython`
module really has, taken from our Linux OBS build. tests/test_obs_scripts.py
runs ClipEm's OBS scripts against a stand-in that allows only these names,
so a call to something obspython doesn't have (e.g. obs.script_path())
fails in CI instead of inside a user's OBS.

obspython is assembled from three places, all read here:
  - obs-install/lib/obs-scripting/obspython.py - the SWIG-generated module
    (functions, constants, and the attributes of its struct classes)
  - obs-src/shared/obs-scripting/obs-scripting-python.c - functions the C
    side adds (script_log, timer_add, obs_enum_sources, ...)
  - obs-src/shared/obs-scripting/obs-scripting-python-frontend.c - the
    obs_frontend_* callback functions

Usage: generate_obspython_api.py [--check]
  --check  exit 1 if the committed snapshot is out of date (release.sh)
"""

import argparse
import ast
import json
import re
import sys

from release_common import ROOT_DIR, SCRIPT_DIR

OBS_INSTALL = SCRIPT_DIR / "obs-install"
OBS_SRC = SCRIPT_DIR / "obs-src" / "shared" / "obs-scripting"
OUT_PATH = ROOT_DIR / "PTMClipEm-App" / "tests" / "obspython_api.json"


def _obs_version():
    cmake = OBS_INSTALL / "lib" / "cmake" / "libobs" / "libobsConfigVersion.cmake"
    match = re.search(r'set\(PACKAGE_VERSION "([^"]+)"\)', cmake.read_text())
    return match.group(1) if match else "unknown"


def _swig_names(path):
    """Top-level functions/constants, and each class's attribute names."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names, classes = set(), {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.ClassDef):
            attrs = set()
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                    attrs.add(item.name)
                elif isinstance(item, ast.Assign):
                    attrs.update(t.id for t in item.targets if isinstance(t, ast.Name))
                elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    attrs.add(item.target.id)
            classes[node.name] = sorted(a for a in attrs if not a.startswith("_") and a != "thisown")
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return {n for n in names if not n.startswith("_")}, classes


def _c_added_names():
    core = (OBS_SRC / "obs-scripting-python.c").read_text()
    frontend = (OBS_SRC / "obs-scripting-python-frontend.c").read_text()
    names = set(re.findall(r'DEF_FUNC\("([A-Za-z_0-9]+)"', core))
    names.update("obs_frontend_" + n for n in re.findall(r"^\s*DEF_FUNC\(([a-z_0-9]+)\)", frontend, re.M))
    return names


def build():
    swig_py = OBS_INSTALL / "lib" / "obs-scripting" / "obspython.py"
    if not swig_py.exists():
        raise SystemExit(f"{swig_py} not found - run Dev/build-obs-from-source-for-linux.sh first.")
    names, classes = _swig_names(swig_py)
    names |= _c_added_names()
    names |= set(classes)  # the struct classes are module attributes too
    return {
        "_comment": "Generated by Dev/generate_obspython_api.py from the Linux OBS build - don't edit.",
        "obs_version": _obs_version(),
        # Added by OBS to each script's own module, not to obspython.
        "script_module_globals": ["script_path"],
        "names": sorted(names),
        "classes": {name: attrs for name, attrs in sorted(classes.items())},
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = json.dumps(build(), indent=1) + "\n"
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != text:
            print(f"{OUT_PATH} is out of date - run Dev/generate_obspython_api.py", file=sys.stderr)
            return 1
        print(f"{OUT_PATH.name} is up to date")
        return 0
    OUT_PATH.write_text(text)
    data = json.loads(text)
    print(f"Wrote {OUT_PATH} (OBS {data['obs_version']}: {len(data['names'])} names, {len(data['classes'])} classes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
